begin;
set local statement_timeout='20s';
do $test$
declare
 u1 uuid:=gen_random_uuid(); u2 uuid:=gen_random_uuid();
 p1 uuid; p2 uuid; j1 uuid:=gen_random_uuid(); j2 uuid:=gen_random_uuid();
 h1 uuid:=gen_random_uuid(); h2 uuid:=gen_random_uuid();
 n integer; ok boolean;
begin
 insert into auth.users(id) values(u1),(u2);
 select participant_id into p1 from seneve.participants where auth_user_id=u1;
 if p1 is null then insert into seneve.participants(auth_user_id,prenom) values(u1,'AUDIT_FICTIF_A') returning participant_id into p1; end if;
 select participant_id into p2 from seneve.participants where auth_user_id=u2;
 if p2 is null then insert into seneve.participants(auth_user_id,prenom) values(u2,'AUDIT_FICTIF_B') returning participant_id into p2; end if;
 insert into seneve.journal_entries(entry_id,participant_id,texte) values(j1,p1,'NOTE_FICTIVE_A'),(j2,p2,'NOTE_FICTIVE_B');
 insert into seneve.help_requests(request_id,participant_id,motif) values(h1,p1,'AIDE_FICTIVE_A'),(h2,p2,'AIDE_FICTIVE_B');
 insert into seneve.help_messages(request_id,auteur,texte) values(h1,'participant','MESSAGE_FICTIF_A'),(h2,'participant','MESSAGE_FICTIF_B');
 perform set_config('request.jwt.claim.sub',u1::text,true);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',u1,'role','authenticated')::text,true);
 execute 'set local role authenticated';
 assert seneve.current_participant_id()=p1,'Identité A incorrecte';
 select count(*) into n from seneve.journal_entries where entry_id=j1; assert n=1,'Note propre A inaccessible';
 select count(*) into n from seneve.journal_entries where entry_id=j2; assert n=0,'Lecture croisée A vers B';
 update seneve.journal_entries set texte='MODIFICATION_INTERDITE' where entry_id=j2; get diagnostics n=row_count; assert n=0,'Modification croisée';
 delete from seneve.journal_entries where entry_id=j2; get diagnostics n=row_count; assert n=0,'Suppression croisée';
 ok:=false;
 begin insert into seneve.journal_entries(participant_id,texte) values(p2,'INSERTION_INTERDITE'); exception when insufficient_privilege then ok:=true; end;
 assert ok,'Insertion pour un autre compte autorisée';
 update seneve.journal_entries set texte='NOTE_FICTIVE_A_MODIFIEE' where entry_id=j1; get diagnostics n=row_count; assert n=1,'Modification propre bloquée';
 select count(*) into n from seneve.help_requests where request_id=h1; assert n=1,'Aide propre inaccessible';
 select count(*) into n from seneve.help_requests where request_id=h2; assert n=0,'Aide étrangère lisible';
 select count(*) into n from seneve.help_messages where request_id=h2; assert n=0,'Message étranger lisible';
 ok:=false;
 begin perform seneve.cancel_help_request(h2); exception when insufficient_privilege then ok:=true; end;
 assert ok,'Annulation aide étrangère autorisée';
 ok:=false;
 begin perform seneve.reply_help_request(h2,gen_random_uuid(),'REPONSE_INTERDITE'); exception when insufficient_privilege then ok:=true; end;
 assert ok,'Réponse aide étrangère autorisée';
 ok:=false;
 begin perform seneve.request_help(gen_random_uuid(),'PARTAGE_INTERDIT',null,array[j2]); exception when insufficient_privilege then ok:=true; end;
 assert ok,'Partage de note étrangère autorisé';
 execute 'reset role';
 perform set_config('request.jwt.claim.sub',u2::text,true);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',u2,'role','authenticated')::text,true);
 execute 'set local role authenticated';
 assert seneve.current_participant_id()=p2,'Identité B incorrecte';
 select count(*) into n from seneve.journal_entries where entry_id=j2; assert n=1,'Note propre B inaccessible';
 select count(*) into n from seneve.journal_entries where entry_id=j1; assert n=0,'Lecture croisée B vers A';
 select count(*) into n from seneve.help_requests where request_id=h1; assert n=0,'Aide A lisible par B';
 execute 'reset role';
 select texte='NOTE_FICTIVE_B' into ok from seneve.journal_entries where entry_id=j2; assert ok,'Note B altérée';
end $test$;
rollback;
select '18 contrôles réussis ; deux identités fictives ; transaction annulée ; aucun envoi' as resultat;